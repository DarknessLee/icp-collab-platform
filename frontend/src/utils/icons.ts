const FALLBACK_ICON: Component = Menu

/** 通过后端菜单 icon 名称解析 Element Plus 图标组件 */
export function resolveIcon(name?: string | null): Component {
  if (!name) return FALLBACK_ICON
  const normalized = String(name).trim()
  if (ICON_MAP[normalized]) return ICON_MAP[normalized]
  const pascal = normalized
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
  return ICON_MAP[pascal] || FALLBACK_ICON
}
